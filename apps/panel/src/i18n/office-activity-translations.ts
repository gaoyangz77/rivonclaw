import type { ActivityCaptionId } from "../lib/office-activity.js";

/**
 * Captions drawn over a character's head in the pixel office while it runs a
 * tool.
 *
 * A separate namespace from `tools.selector.name` on purpose. That map is the
 * vocabulary of the tool picker - noun phrases naming a capability ("Get
 * Order"), some of them long enough to be a sentence - and the picker's UI
 * depends on exactly those words. A head caption is a different register: it
 * says what someone is doing right now, in as few characters as will sit above
 * a 16-pixel sprite. The two are kept side by side, grouped in the same order,
 * so a tool added to one is visibly missing from the other.
 *
 * Keys are caption ids, not tool ids, because several tools are the same act to
 * a viewer; `lib/office-activity.ts` owns the tool-to-caption map and is where
 * a new tool gets attached to one of these.
 *
 * ## Wording
 *
 * Present-progressive and plain. The idle labels next door are allowed to be
 * playful - a character with no work can hum - but real work is not the place
 * for a joke that will be read a thousand times in one screensaver.
 *
 * No symbols. The office font (FS Pixel Sans Unicode) covers 6701 codepoints
 * and none of the obvious decorations - no musical notes, no stars, no coffee
 * cup - so any of them would be drawn by the system fallback and land as a
 * smooth glyph inside pixel text. Chinese and Thai already fall back that way
 * for their whole caption, exactly as the office's existing labels do.
 */
function build(captions: Record<ActivityCaptionId, string>) {
  return { tools: { activity: captions } };
}

